const modal=document.getElementById("calculatorModal");
const form=document.getElementById("calculatorForm");
const fieldsBox=document.getElementById("calculatorFields");
const resultBox=document.getElementById("calculatorResult");
let activeCalculator=null;
let activeFilter="all";

function money(value){
  return new Intl.NumberFormat("en-IN",{style:"currency",currency:"INR",maximumFractionDigits:2}).format(value);
}
function addField(field){
  const wrapper=document.createElement("div");
  wrapper.className="field"+(field.type==="text"?" full":"");
  const label=document.createElement("label");
  label.htmlFor=field.id;label.textContent=field.label;wrapper.appendChild(label);
  let input;
  if(field.type==="select"){
    input=document.createElement("select");
    field.options.forEach(([value,text])=>{const option=document.createElement("option");option.value=value;option.textContent=text;input.appendChild(option);});
  }else{
    input=document.createElement("input");input.type=field.type;
    if(field.min!==undefined)input.min=field.min;
    if(field.max!==undefined)input.max=field.max;
    if(field.step!==undefined)input.step=field.step;
    if(field.placeholder)input.placeholder=field.placeholder;
  }
  input.id=field.id;input.name=field.id;input.required=Boolean(field.required);
  wrapper.appendChild(input);fieldsBox.appendChild(wrapper);
}
function openCalculator(name){
  const definition=definitions[name];if(!definition)return;
  activeCalculator=name;fieldsBox.replaceChildren();form.reset();resultBox.hidden=true;resultBox.replaceChildren();
  document.getElementById("modalTitle").textContent=definition.title;
  document.getElementById("modalDescription").textContent=definition.description;
  definition.fields.forEach(addField);
  modal.hidden=false;document.body.style.overflow="hidden";
  const first=fieldsBox.querySelector("input,select");if(first)first.focus();
}
function closeCalculator(){modal.hidden=true;document.body.style.overflow="";}

document.querySelectorAll(".open-calculator").forEach(button=>button.addEventListener("click",()=>openCalculator(button.dataset.calculator)));
document.getElementById("closeModal").addEventListener("click",closeCalculator);
modal.addEventListener("click",event=>{if(event.target===modal)closeCalculator();});
document.addEventListener("keydown",event=>{if(event.key==="Escape"&&!modal.hidden)closeCalculator();});

form.addEventListener("submit",event=>{
  event.preventDefault();if(!activeCalculator)return;
  const definition=definitions[activeCalculator],values={};
  for(const field of definition.fields){
    const element=form.elements.namedItem(field.id);
    if(field.type==="text"){values[field.id]=element.value.trim();if(!values[field.id]){element.focus();return;}}
    else{const value=Number(element.value);if(element.value===""||!Number.isFinite(value)||value<0||(field.max!==undefined&&value>Number(field.max))){element.focus();element.reportValidity?.();return;}values[field.id]=value;}
  }
  if(activeCalculator==="unit"&&(values.qty1<=0||values.qty2<=0)){alert("Pack quantities must be greater than zero.");return;}
  const output=definition.calculate(values);
  resultBox.replaceChildren();
  const heading=document.createElement("h3");heading.textContent="YOUR ESTIMATE";
  const main=document.createElement("div");main.className="result-main";main.textContent=output.main;
  const detail=document.createElement("div");detail.className="result-detail";detail.textContent=output.detail;
  resultBox.append(heading,main,detail);resultBox.hidden=false;
});

function filterCards(){
  const query=document.getElementById("searchInput").value.trim().toLowerCase();
  let visible=0;
  document.querySelectorAll(".tool-card").forEach(card=>{
    const matchesCategory=activeFilter==="all"||card.dataset.category===activeFilter;
    const matchesSearch=(card.dataset.search+" "+card.textContent).toLowerCase().includes(query);
    card.hidden=!(matchesCategory&&matchesSearch);if(!card.hidden)visible++;
  });
  const noResults=document.getElementById("noResults");noResults.hidden=visible!==0;
  if(visible===0)noResults.textContent=(translations[document.getElementById("languageSelect").value]||translations.en).noResults;
}
document.getElementById("searchInput").addEventListener("input",filterCards);
document.querySelectorAll(".filter-chip").forEach(button=>button.addEventListener("click",()=>{
  activeFilter=button.dataset.filter;
  document.querySelectorAll(".filter-chip").forEach(chip=>chip.classList.toggle("active",chip===button));
  filterCards();
}));

function setLanguage(language){
  const dictionary=translations[language]||translations.en;
  document.documentElement.lang=language;
  document.querySelectorAll("[data-i18n]").forEach(element=>{
    const key=element.dataset.i18n;if(dictionary[key]!==undefined)element.innerHTML=dictionary[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(element=>{
    const key=element.dataset.i18nPlaceholder;if(dictionary[key]!==undefined)element.placeholder=dictionary[key];
  });
  filterCards();
}
document.getElementById("languageSelect").addEventListener("change",event=>setLanguage(event.target.value));
